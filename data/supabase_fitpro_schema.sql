-- Tipos ENUM
DO $$ BEGIN
  CREATE TYPE perfil_usuario AS ENUM ('master', 'admin', 'personal', 'aluno', 'usuario');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

DO $$ BEGIN
  CREATE TYPE tipo_evento_agenda AS ENUM ('treino', 'avaliacao', 'nutricao');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

DO $$ BEGIN
  CREATE TYPE status_pagamento AS ENUM ('pago', 'pendente', 'atrasado', 'cancelado');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

-- Função updated_at
CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

-- -----------------------------------------------------------------------------
-- academias
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.academias (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome        VARCHAR(200) NOT NULL,
  slug        VARCHAR(80),
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_academias_slug UNIQUE (slug)
);

-- -----------------------------------------------------------------------------
-- usuarios (login da app via JWT + bcrypt)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.usuarios (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome         VARCHAR(120) NOT NULL,
  email        VARCHAR(160) NOT NULL,
  senha_hash   VARCHAR(255) NOT NULL,
  perfil       perfil_usuario NOT NULL DEFAULT 'aluno',
  ativo        BOOLEAN NOT NULL DEFAULT true,
  academia_id  INTEGER NOT NULL REFERENCES public.academias (id) ON DELETE RESTRICT,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_usuarios_email UNIQUE (email)
);

CREATE INDEX IF NOT EXISTS idx_usuarios_academia ON public.usuarios (academia_id);
CREATE INDEX IF NOT EXISTS idx_usuarios_email_lower ON public.usuarios (lower(email));

DROP TRIGGER IF EXISTS tr_usuarios_updated_at ON public.usuarios;
CREATE TRIGGER tr_usuarios_updated_at
  BEFORE UPDATE ON public.usuarios
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- -----------------------------------------------------------------------------
-- usuarios_login_log (auditoria de acessos / logins)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.usuarios_login_log (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     INTEGER NOT NULL REFERENCES public.usuarios (id) ON DELETE CASCADE,
  academia_id INTEGER NOT NULL REFERENCES public.academias (id) ON DELETE CASCADE,
  email       VARCHAR(160) NOT NULL,
  ip          TEXT,
  user_agent  TEXT,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_usuarios_login_log_created_at ON public.usuarios_login_log (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_usuarios_login_log_user ON public.usuarios_login_log (academia_id, user_id, created_at DESC);

-- -----------------------------------------------------------------------------
-- alunos
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.alunos (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  academia_id  INTEGER NOT NULL REFERENCES public.academias (id) ON DELETE CASCADE,
  nome         VARCHAR(120) NOT NULL,
  email        VARCHAR(160),
  telefone     VARCHAR(40),
  objetivo     VARCHAR(255),
  plano        VARCHAR(120),
  status       VARCHAR(40) DEFAULT 'ativo',
  peso         NUMERIC(6, 2),
  altura       NUMERIC(5, 2),
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_alunos_academia ON public.alunos (academia_id);

DROP TRIGGER IF EXISTS tr_alunos_updated_at ON public.alunos;
CREATE TRIGGER tr_alunos_updated_at
  BEFORE UPDATE ON public.alunos
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- -----------------------------------------------------------------------------
-- treinos
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.treinos (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  academia_id  INTEGER NOT NULL REFERENCES public.academias (id) ON DELETE CASCADE,
  user_id      INTEGER NOT NULL REFERENCES public.usuarios (id) ON DELETE CASCADE,
  nome         VARCHAR(200) NOT NULL,
  categoria    VARCHAR(80),
  status       VARCHAR(40) NOT NULL DEFAULT 'ativo',
  exercicios   TEXT,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
