DROP TRIGGER IF EXISTS tr_treinos_updated_at ON public.treinos;
CREATE TRIGGER tr_treinos_updated_at
  BEFORE UPDATE ON public.treinos
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- -----------------------------------------------------------------------------
-- planos_academia
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.planos_academia (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  academia_id  INTEGER NOT NULL REFERENCES public.academias (id) ON DELETE CASCADE,
