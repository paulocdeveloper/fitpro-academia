CREATE TRIGGER tr_planos_academia_updated_at
  BEFORE UPDATE ON public.planos_academia
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- -----------------------------------------------------------------------------
-- pagamentos
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.pagamentos (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  academia_id     INTEGER NOT NULL REFERENCES public.academias (id) ON DELETE CASCADE,
  aluno_id        INTEGER REFERENCES public.alunos (id) ON DELETE SET NULL,
  aluno_nome      VARCHAR(120) NOT NULL,
  valor           NUMERIC(10, 2) NOT NULL CHECK (valor >= 0),
  vencimento      DATE NOT NULL,
  data_pagamento  DATE,
  status          status_pagamento NOT NULL DEFAULT 'pendente',
  metodo          VARCHAR(60),
  observacoes     VARCHAR(500),
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_pagamentos_academia ON public.pagamentos (academia_id);
CREATE INDEX IF NOT EXISTS idx_pagamentos_aluno ON public.pagamentos (aluno_id);
CREATE INDEX IF NOT EXISTS idx_pagamentos_status ON public.pagamentos (academia_id, status);

DROP TRIGGER IF EXISTS tr_pagamentos_updated_at ON public.pagamentos;
CREATE TRIGGER tr_pagamentos_updated_at
  BEFORE UPDATE ON public.pagamentos
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- -----------------------------------------------------------------------------
-- agenda_eventos
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.agenda_eventos (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  academia_id   INTEGER NOT NULL REFERENCES public.academias (id) ON DELETE CASCADE,
  data_evento   DATE NOT NULL,
  horario       VARCHAR(5) NOT NULL,
  tipo          tipo_evento_agenda NOT NULL,
  aluno_nome    VARCHAR(120) NOT NULL,
  aluno_id      INTEGER REFERENCES public.alunos (id) ON DELETE SET NULL,
  duracao       INTEGER NOT NULL DEFAULT 60 CHECK (duracao > 0),
  observacoes   VARCHAR(500),
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_agenda_academia_data ON public.agenda_eventos (academia_id, data_evento);
CREATE INDEX IF NOT EXISTS idx_agenda_aluno ON public.agenda_eventos (aluno_id);

DROP TRIGGER IF EXISTS tr_agenda_eventos_updated_at ON public.agenda_eventos;
CREATE TRIGGER tr_agenda_eventos_updated_at
  BEFORE UPDATE ON public.agenda_eventos
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- -----------------------------------------------------------------------------
-- dietas + alimentos (módulo nutrição)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.dietas (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  academia_id     INTEGER NOT NULL REFERENCES public.academias (id) ON DELETE CASCADE,
  aluno_id        INTEGER REFERENCES public.alunos (id) ON DELETE SET NULL,
  titulo          VARCHAR(200) NOT NULL,
  aluno_nome      VARCHAR(120),
  objetivo        VARCHAR(255),
  proteinas       INTEGER NOT NULL DEFAULT 0 CHECK (proteinas >= 0),
  carbos          INTEGER NOT NULL DEFAULT 0 CHECK (carbos >= 0),
  gorduras        INTEGER NOT NULL DEFAULT 0 CHECK (gorduras >= 0),
  refeicoes_json  TEXT NOT NULL DEFAULT '[]',
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_dietas_academia ON public.dietas (academia_id);
CREATE INDEX IF NOT EXISTS idx_dietas_aluno ON public.dietas (aluno_id);

DROP TRIGGER IF EXISTS tr_dietas_updated_at ON public.dietas;
CREATE TRIGGER tr_dietas_updated_at
  BEFORE UPDATE ON public.dietas
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

CREATE TABLE IF NOT EXISTS public.alimentos (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  academia_id      INTEGER NOT NULL REFERENCES public.academias (id) ON DELETE CASCADE,
  nome             VARCHAR(200) NOT NULL,
  kcal_100g        INTEGER NOT NULL CHECK (kcal_100g >= 0),
  proteinas_100g   NUMERIC(6, 2) NOT NULL DEFAULT 0,
  carbos_100g      NUMERIC(6, 2) NOT NULL DEFAULT 0,
  gorduras_100g    NUMERIC(6, 2) NOT NULL DEFAULT 0,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_alimentos_academia_nome UNIQUE (academia_id, nome)
);

CREATE INDEX IF NOT EXISTS idx_alimentos_academia ON public.alimentos (academia_id);

DROP TRIGGER IF EXISTS tr_alimentos_updated_at ON public.alimentos;
CREATE TRIGGER tr_alimentos_updated_at
  BEFORE UPDATE ON public.alimentos
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

